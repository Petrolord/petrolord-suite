// Compact Pore Pressure Studio validation fixture from the Ekene kit
// (ekene-demo-v4): Ekene-1's DEPT, GR, RHOB and DT, every 4th sample
// (0.6096 m, values copied as written), and the kit's designed prognosis,
// the truth the shale-pressure gate checks against.
//   node tools/validation/porepressure/make-ekene1-fixture.mjs [kitDir]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const kit = process.argv[2] || path.resolve(HERE, '../../../dist-demo/ekene-demo-v4');
const out = path.resolve(HERE, '../../../src/pages/apps/PorePressureStudio/__tests__/fixtures');
const EVERY = 4;
const KEEP = ['DEPT', 'GR', 'RHOB', 'DT'];

const las = fs.readFileSync(path.join(kit, '01-wells/Ekene-1.las'), 'utf8').split(/\r?\n/);
const curveStart = las.findIndex((l) => /^~C/i.test(l));
const asciiStart = las.findIndex((l) => /^~A/i.test(l));
const curveLines = las.slice(curveStart + 1, asciiStart).filter((l) => l.trim() && !l.startsWith('#'));
const names = curveLines.map((l) => l.trim().split(/[\s.]/)[0].toUpperCase());
const cols = KEEP.map((k) => names.indexOf(k));
if (cols.some((c) => c < 0)) throw new Error(`Ekene-1.las lacks one of ${KEEP.join(', ')}`);
const rows = las.slice(asciiStart + 1).filter((l) => l.trim());
const kept = rows.filter((_, i) => i % EVERY === 0).map((l) => l.trim().split(/\s+/));
const header = las.slice(0, curveStart + 1)
  .map((l) => (/^\s*STEP\s*\./.test(l) ? l.replace(/0\.1524/, (0.1524 * EVERY).toFixed(4)) : l))
  .map((l) => (/^\s*STOP\s*\./.test(l) ? l.replace(/[\d.]+(?=\s+:)/, kept[kept.length - 1][0]) : l));
const text = [
  `# Generated by tools/validation/porepressure/make-ekene1-fixture.mjs from ekene-demo-v4 01-wells/Ekene-1.las (every ${EVERY}th sample)`,
  ...header,
  ...cols.map((c) => curveLines[c]),
  '~Ascii',
  ...kept.map((r) => cols.map((c) => r[c].padStart(12)).join(' ')),
  '',
].join('\n');
fs.writeFileSync(path.join(out, 'ekene-1-pp.las'), text);
fs.copyFileSync(path.join(kit, '05-pressure/ekene-1-designed-prognosis.csv'), path.join(out, 'ekene-1-designed-prognosis.csv'));
console.log(`${kept.length} samples -> ${path.join(out, 'ekene-1-pp.las')}`);
