// Refresh the "Data for this episode" block in every tutorial script under
// docs/tutorials/scripts/ from the generated kit's episode notes, so the
// scripts and the kit cannot drift apart. Idempotent: the block sits between
// KIT-DATA markers and is replaced whole; a script without markers gets the
// block inserted before its script section.
//
//   npx tsx tools/demo-dataset/generate.mjs
//   node tools/demo-dataset/sync-episode-scripts.mjs
//
// Fails if a script has no matching episode note, or a note no longer parses.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const EPISODES = path.join(ROOT, 'dist-demo', 'ekene-demo-v1', 'episodes');
const SCRIPTS = path.join(ROOT, 'docs', 'tutorials', 'scripts');
const RELEASE = 'https://github.com/Petrolord/petrolord-suite/releases/tag/ekene-demo-v1';
const START = '<!-- KIT-DATA:START (generated by tools/demo-dataset/sync-episode-scripts.mjs; do not edit by hand) -->';
const END = '<!-- KIT-DATA:END -->';

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const inline = (s) => esc(s).replace(/`([^`]+)`/g, '<code>$1</code>');

function parseNote(text, name) {
  const files = [...text.matchAll(/^- `([^`]+)`: (.+)$/gm)].map((m) => [m[1], m[2]]);
  const note = (text.split('## Before the take')[1] || '').split('Kit: `')[0].trim();
  if (!files.length || !note) throw new Error(`${name}: the note no longer parses (files ${files.length}, note ${note.length} chars).`);
  return { files, note };
}

function block(md, { files, note }) {
  const rows = files.map(([f, why]) => `          <tr><td><code>${esc(f)}</code></td><td>${inline(why)}</td></tr>`).join('\n');
  return `  ${START}
  <div class="brief kit-data">
    <div>
      <h2 class="block">Data for this episode</h2>
      <p>Everything this episode loads comes from the Ekene demonstration dataset, kit <code>ekene-demo-v1</code>. Download <code>ekene-demo-v1-kit.zip</code> (and, for the seismic episodes, <code>ekene-demo-v1-seismic-full.zip</code>) from <a href="${RELEASE}">the release page</a> and start with <code>00-START-HERE.md</code>. This block is generated from <code>episodes/${md}</code> in the kit, so the two always agree.</p>
      <table class="say">
        <thead><tr><th>File</th><th>What it is for</th></tr></thead>
        <tbody>
${rows}
        </tbody>
      </table>
    </div>
    <div>
      <h2 class="block">Before the take</h2>
      <div class="note">${inline(note)}</div>
    </div>
  </div>
  ${END}
`;
}

const notes = fs.readdirSync(EPISODES);
let n = 0;
for (const script of fs.readdirSync(SCRIPTS).filter((f) => f.endsWith('-script.html')).sort()) {
  const md = `${script.replace(/-script\.html$/, '')}.md`;
  if (!notes.includes(md)) throw new Error(`${script}: no episode note ${md} in the kit.`);
  const b = block(md, parseNote(fs.readFileSync(path.join(EPISODES, md), 'utf8'), md));
  const p = path.join(SCRIPTS, script);
  let html = fs.readFileSync(p, 'utf8');
  const i = html.indexOf(START);
  if (i >= 0) {
    const j = html.indexOf(END, i);
    if (j < 0) throw new Error(`${script}: KIT-DATA start marker without an end.`);
    const lineStart = html.lastIndexOf('\n', i) + 1;
    html = html.slice(0, lineStart) + b + html.slice(html.indexOf('\n', j) + 1);
  } else {
    const anchor = '  <div class="script">';
    if (html.split(anchor).length !== 2) throw new Error(`${script}: cannot find the script section to insert before.`);
    html = html.replace(anchor, `${b}\n${anchor}`);
  }
  fs.writeFileSync(p, html);
  n += 1;
}
console.log(`${n} tutorial scripts refreshed from the kit's episode notes`);
