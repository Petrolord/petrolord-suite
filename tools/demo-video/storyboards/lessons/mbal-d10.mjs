// Material Balance with Petrolord, Lesson D10: a dry gas reservoir (the
// Oboro gas scenario, 60 Bscf, volumetric). A gas case, Z and Bg on the rows,
// the regression, the p/z line and why it reads high, and the Cole plot.
import {
  login, expectText, openStudio, deleteCases, createCase, confirmCase, dropFile, saveData, setPvt, runMbal, showPlot,
  t, tab, OBORO, OBORO_FILE, mbalLessonMeta,
} from './mbal-common.mjs';

export default {
  id: 'lesson-mbal-d10',
  ...mbalLessonMeta(10, 'D', 'A gas reservoir: *p/z and Cole*', 'The Oboro gas scenario: gas in place, the p/z line and the Cole check'),
  async setup(d, shared) {
    d.page.on('dialog', (dg) => dg.accept().catch(() => {}));
    await login(d.page, shared.baseUrl, shared.env);
    await deleteCases(d, shared, /^Lesson D10/);
    await openStudio(d, shared);
    await d.page.evaluate(() => window.__demo.moveTo(900, 500, 10));
  },
  steps: [
    { id: 'case', chapter: 'A gas case', chapterSub: 'The Oboro gas scenario',
      say: 'The Oboro Sand is gas-bearing on the Ekene logs. This scenario, generated by the engine, makes it a dry gas reservoir of sixty billion standard cubic feet with no aquifer. A gas case needs no bubble point: four thousand three hundred and fifty psia, two hundred and five degrees Fahrenheit, and a water saturation of nought point two two.',
      sub: 'The Oboro Sand is gas-bearing on the Ekene logs. This scenario, generated by the engine, makes it a dry gas reservoir of 60 billion standard cubic feet with no aquifer. A gas case needs no bubble point: 4,350 psia, 205 °F, and a water saturation of 0.22.',
      do: async (d) => {
        await d.click(d.page.getByRole('button', { name: 'Create a case' }));
        await d.page.locator('#name').waitFor();
        await createCase(d, 'Lesson D10: Oboro gas', { onCamera: true, open: false, fluid: 'Gas reservoir', c: OBORO.c, reservoir: 'Oboro Sand (gas scenario)' });
        await confirmCase(d, { onCamera: true });
      } },
    { id: 'data', chapter: 'The history', chapterSub: 'Gas, water, Z and Bg',
      say: 'The history carries the cumulative gas and water, and the Z factor and gas formation volume factor at each survey, so again the rows bring their own PVT.',
      do: async (d) => {
        await dropFile(d, OBORO_FILE, { onCamera: true });
        await d.highlight(t(d, 'mbal-import-mapping'));
        await d.sleep(3000);
        await d.unhighlight();
        await saveData(d, { onCamera: true });
        await setPvt(d, OBORO.pvt);
      } },
    { id: 'run', chapter: 'Gas in place', chapterSub: 'F against Eg',
      say: 'Run it. For gas, F is the produced gas at its formation volume factor, and the expansion is that of the gas, with a small share for rock and water. Sixty point nought nought billion standard cubic feet at an r squared of one, almost all of it gas expansion drive.',
      sub: 'Run it. For gas, F is the produced gas at its formation volume factor, and the expansion is that of the gas, with a small share for rock and water. 60.00 billion standard cubic feet at an r² of one, almost all of it gas expansion drive.',
      do: async (d) => {
        await runMbal(d, { onCamera: true });
        await expectText(d, t(d, 'mbal-result-card'), /OGIP\s*60\.00 Bscf[\s\S]*Regression r2\s*1\.000000[\s\S]*Gas expansion \(GDI\)\s*0\.992/, 'ogip');
        await d.highlight(t(d, 'mbal-result-card').locator('div.grid').first());
        await d.sleep(3500);
        await d.unhighlight();
      } },
    { id: 'pz', chapter: 'The p/z plot', chapterSub: 'And why it reads high',
      say: 'The classic check is p over z against cumulative gas: a straight line for a volumetric gas reservoir, reaching zero at the gas in place. Extrapolated, this line reaches sixty point five six billion, a little high, because plain p over z leaves out the expansion of the rock and the water. The corrected line of Ramagost and Farshad puts it back, and the run\'s sixty point nought nought is marked.',
      sub: 'The classic check is p/z against cumulative gas: a straight line for a volumetric gas reservoir, reaching zero at the gas in place. Extrapolated, this line reaches 60.56 billion, a little high, because plain p/z leaves out the expansion of the rock and the water. The corrected line of Ramagost and Farshad puts it back, and the run\'s 60.00 is marked.',
      do: async (d) => {
        await d.click(tab(d, 'Plots'));
        const c = await showPlot(d, 'pz');
        await expectText(d, 'mbal-plot-notes-pz', /p\/z line to zero: 60\.56 Bscf \(apparent\)[\s\S]*OGIP of this run: 60\.00 Bscf/, 'p/z');
        await d.highlight(c);
        await d.sleep(7000);
        await d.unhighlight();
      } },
    { id: 'cole', chapter: 'The Cole plot', chapterSub: 'The gas Campbell',
      say: 'The Cole plot is the gas form of Campbell: F over E g against the cumulative gas. Level, as here, means no water drive. A line that rises, or rises and then falls, is the mark of an aquifer, and plain p over z would then overstate the gas in place by far more.',
      do: async (d) => {
        const c = await showPlot(d, 'cole');
        await d.highlight(c);
        await d.sleep(5000);
        await d.unhighlight();
      } },
    { id: 'next', chapter: 'Next', chapterSub: 'When the data changes',
      say: 'Next, Module E: three more years of Ekene data under a waterflood, and injection in the balance.',
      do: async (d) => { await d.sleep(2000); } },
  ],
};
