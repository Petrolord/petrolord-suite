#!/usr/bin/env python3
"""Generate exact pre-state rollback SQL for the 2026-10 security migrations.

Run BEFORE applying, from the Suite checkout linked to the project:
  python3 tools/security/2026-10/rollback/gen_rollback.py
Reads the live catalog with read-only SELECTs (supabase db query --linked) and
writes NN_*.rollback.sql next to this file. Each rollback restores, for the
objects its migration touches: table RLS flag, anon/authenticated table
grants, every policy (exact text), function bodies and EXECUTE grants.
Generated 2026-10-14 BEFORE any of 01-05 was applied: do not regenerate after
applying (it would snapshot the new state). The generated files contain no begin/commit (run them with
supabase db query --linked -f, one implicit transaction)."""
import json, subprocess, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
MIG = os.path.normpath(os.path.join(HERE, '..', '..', '..', '..', 'supabase', 'migrations'))

def q(sql):
    out = subprocess.run(['supabase', 'db', 'query', '--linked', sql, '-o', 'json'],
                         capture_output=True, text=True, check=True).stdout
    return json.loads(out[out.index('{'):])['rows']

def lit(s):
    return "'" + s.replace("'", "''") + "'"

def ident(s):
    return '"' + s.replace('"', '""') + '"'

def table_block(tables, schema='public', only_policies=None, drop_all=True, policies_only=()):
    out = []
    tl = ','.join(lit(t) for t in tables)
    rls = {r['relname']: r for r in q(f"""select c.relname, c.relrowsecurity from pg_class c
        join pg_namespace n on n.oid=c.relnamespace where n.nspname={lit(schema)} and c.relname in ({tl})""")}
    grants = q(f"""select table_name, grantee, string_agg(privilege_type, ', ' order by privilege_type) privs
        from information_schema.role_table_grants where table_schema={lit(schema)} and table_name in ({tl})
        and grantee in ('anon','authenticated') group by 1,2""")
    pols = q(f"""select tablename, policyname, permissive, roles::text roles, cmd, qual, with_check
        from pg_policies where schemaname={lit(schema)} and tablename in ({tl}) order by 1,2""")
    for t in tables:
        if t not in rls:
            out.append(f'-- {schema}.{t}: absent at snapshot time'); continue
        fq = f'{schema}.{ident(t)}'
        out.append(f'-- ---- {schema}.{t}')
        if schema == 'public' and t not in policies_only:
            out.append(f"alter table {fq} {'enable' if rls[t]['relrowsecurity'] else 'disable'} row level security;")
            out.append(f'revoke all on table {fq} from anon, authenticated;')
            for g in grants:
                if g['table_name'] == t:
                    out.append(f"grant {g['privs']} on table {fq} to {g['grantee']};")
        if drop_all:
            out.append(f"""do $r$ declare p record; begin
  for p in select policyname from pg_policies where schemaname={lit(schema)} and tablename={lit(t)} loop
    execute format('drop policy %I on {schema}.%I', p.policyname, {lit(t)});
  end loop; end $r$;""")
        for p in pols:
            if p['tablename'] != t: continue
            if only_policies is not None and p['policyname'] not in only_policies: continue
            if not drop_all:
                out.append(f"drop policy if exists {ident(p['policyname'])} on {fq};")
            roles = ', '.join(ident(r) if r != 'public' else 'public' for r in p['roles'].strip('{}').split(','))
            s = f"create policy {ident(p['policyname'])} on {fq} as {p['permissive'].lower()} for {p['cmd'].lower()} to {roles}"
            if p['qual'] is not None: s += f" using ({p['qual']})"
            if p['with_check'] is not None: s += f" with check ({p['with_check']})"
            out.append(s + ';')
    return '\n'.join(out)

def func_block(sigs):
    out = []
    for sig in sigs:
        rows = q(f"""select pg_get_functiondef(p.oid) def,
            has_function_privilege('anon', p.oid, 'EXECUTE') a,
            has_function_privilege('authenticated', p.oid, 'EXECUTE') u
            from pg_proc p where p.oid = to_regprocedure({lit(sig)})""")
        if not rows:
            out.append(f'-- {sig}: absent at snapshot time'); continue
        r = rows[0]
        out.append(f'-- ---- {sig}')
        out.append(r['def'].rstrip() + ';')
        out.append(f'revoke execute on function {sig} from public, anon, authenticated;')
        roles = [x for x, ok in (('anon', r['a']), ('authenticated', r['u'])) if ok]
        if roles: out.append(f"grant execute on function {sig} to {', '.join(roles)};")
        out.append(f'grant execute on function {sig} to service_role;')
    return '\n'.join(out)

def write(name, title, body):
    path = os.path.join(HERE, name)
    with open(path, 'w') as f:
        f.write(f"-- ROLLBACK for {title}\n-- GENERATED by gen_rollback.py from the live catalog BEFORE apply. Re-opens what the migration closed;\n"
                f"-- emergency use only. Prefer restoring the one table or function that broke (copy its block).\n"
                f"-- No begin/commit: run with `supabase db query --linked -f {name}`.\n\n{body}\n")
    print('wrote', path)

def policy_tables_of(path):
    s = open(os.path.join(MIG, path)).read()
    return sorted(set(re.findall(r'on public\.([a-z_0-9]+)', s)) | set(re.findall(r'table public\.([a-z_0-9]+)', s)))

# 01: only is_super_admin changes behaviour (new objects are inert)
write('01.rollback.sql', '20261014121000 (is_super_admin and handle_new_user back to the live bodies; platform_admins left in place)',
      func_block(['public.is_super_admin()', 'public.handle_new_user()']))

def transitional_trigger():
    m1 = open(os.path.join(MIG, '20261014121000_security_01_platform_admins_and_invitation_rpcs.sql')).read()
    i = m1.index('CREATE OR REPLACE FUNCTION public.handle_new_user()')
    j = m1.index('$function$;', i) + len('$function$;')
    return m1[i:j]

# 02
write('02.rollback.sql', '20261014121100 (invitation lockdown)',
      table_block(['invitations']) + "\nalter table public.invitations alter column invited_by drop default;\n" +
      func_block(['public.add_user_to_organization(uuid,uuid,text)', 'public.enable_hse_for_organization(uuid)']) +
      '\n-- ---- public.handle_new_user(): back to the 01 TRANSITIONAL body (token or legacy path), so the\n'
      '-- HSE page and Suite function shipped after 01 keep working. Copied from the 01 migration file.\n' +
      transitional_trigger())

# 03
write('03.rollback.sql', '20261014121200 (users guard, seats, invited rows)',
      "drop trigger if exists users_guard_privileged_columns on public.users;\n"
      "drop trigger if exists platform_admins_mirror on public.platform_admins;\n" +
      table_block(['users', 'organization_members']) + '\n' +
      func_block(['public.assign_app_seat(uuid,text,uuid)', 'public.unassign_app_seat(uuid,text,uuid)']))

# 04
t04 = [t for t in policy_tables_of('20261014121300_security_04_rls_off_tables.sql') if t not in ('projects', 'pm_resources_x')]
t04 = [t for t in t04 if t != 'projects']
write('04.rollback.sql', '20261014121300 (RLS-off tables)',
      table_block(t04) + '\n' + func_block(['public.manual_verify_quote(text,uuid)']))

# 05
s05 = open(os.path.join(MIG, '20261014121400_security_05_policy_fixes.sql')).read()
userrole = [r['tablename'] for r in q("""select distinct tablename from pg_policies where schemaname='public'
    and (coalesce(qual,'') like '%get_my_claim(''user_role''%' or coalesce(with_check,'') like '%get_my_claim(''user_role''%')""")]
t05 = sorted((set(re.findall(r'on public\.([a-z_0-9]+)', s05)) | set(re.findall(r'table public\.([a-z_0-9]+)', s05))
              | {'quickvol_workspaces', 'quickvol_workspace_members', 'quickvol_activity_logs', 'quickvol_comments', 'quickvol_versions'}
              | set(userrole)))
storage_names = sorted(set(re.findall(r'drop policy if exists "([^"]+)" on storage\.objects', s05)))
storage_new = sorted(set(re.findall(r'drop policy if exists ([a-z_0-9]+) on storage\.objects', s05)))
QV = {'quickvol_workspaces', 'quickvol_workspace_members', 'quickvol_activity_logs', 'quickvol_comments', 'quickvol_versions'}
# tables 04 also covers: 05's rollback restores their policies only (04's rollback owns RLS and grants)
body = table_block(t05, policies_only=QV | set(t04)) + '\n-- ---- storage.objects (only the policies 05 replaces)\n'
body += '\n'.join(f'drop policy if exists {n} on storage.objects;' for n in storage_new) + '\n'
body += table_block(['objects'], schema='storage', only_policies=set(storage_names), drop_all=False) + '\n'
body += func_block(['public.get_users_for_organization(uuid)', 'public.delete_organization(uuid)',
                    'public.hse_complete_org_setup(uuid)', 'public.update_last_accessed_app(text)'])
write('05.rollback.sql', '20261014121400 (policy fixes)', body)
