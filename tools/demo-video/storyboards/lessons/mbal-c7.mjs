// Material Balance with Petrolord, Lesson C7: the gas cap ratio m (Ekene
// gas-cap scenario). What m is, what the gas cap drive index shows, how the
// oil in place moves with m, and fitting m in a history match.
import {
  login, expectText, deleteCases, seedCase, setCarterTracy, setPvt, runMbal, t, tab, GASCAP, GASCAP_FILE, mbalLessonMeta,
} from './mbal-common.mjs';

const ooip = (d) => t(d, 'mbal-result-card').getByText(/^\d[\d.,]* (MMSTB|MSTB)$/).first();
const seg = (d, name) => d.page.getByRole('radio', { name }).or(d.page.getByRole('button', { name, exact: true })).first();
const setM = async (d, m, onCamera = true) => setPvt(d, { api: null, salinity: null, cf: null, cw: null, m }, { onCamera });

export default {
  id: 'lesson-mbal-c7',
  ...mbalLessonMeta(7, 'C', 'The gas cap ratio *m*', 'An oil rim under a gas cap: what m is, how it moves the answer, and fitting it'),
  async setup(d, shared) {
    d.page.on('dialog', (dg) => dg.accept().catch(() => {}));
    await login(d.page, shared.baseUrl, shared.env);
    await deleteCases(d, shared, /^Lesson C7/);
    await seedCase(d, shared, 'Lesson C7: gas-cap scenario', {
      file: GASCAP_FILE, fluid: 'Oil with gas cap', c: GASCAP.c, pvt: GASCAP.pvt, reservoir: 'Ekene Sand (gas-cap scenario)',
      before: (dd) => setCarterTracy(dd, GASCAP.ct),
    });
    await d.page.evaluate(() => window.__demo.moveTo(900, 500, 10));
  },
  steps: [
    { id: 'case', chapter: 'An oil rim under a gas cap', chapterSub: 'The Ekene gas-cap scenario',
      say: 'Module C works on the Ekene gas-cap scenario, generated by the engine from a tank of eighteen million stock tank barrels with a gas cap and an edge aquifer. A gas cap means the oil was saturated at discovery: the bubble point equals the initial pressure, three thousand two hundred psia.',
      do: async (d) => {
        await d.highlight(t(d, 'mbal-case-summary'));
        await d.sleep(4000);
        await d.unhighlight();
      } },
    { id: 'm', chapter: 'The ratio m', chapterSub: 'Gas cap over oil, at reservoir conditions',
      say: 'm is the reservoir volume of the gas cap over the reservoir volume of the oil. It usually comes from the gas and oil columns on the logs and the map. For this case it is nought point four five. As the pressure falls, the gas cap expands and pushes oil towards the wells: the gas cap drive.',
      do: async (d) => {
        await d.click(tab(d, 'PVT'));
        await t(d, 'mbal-pvt-cf').waitFor({ timeout: 60000 });
        await d.sleep(1000);
        const m = d.page.locator('#gasCapM');
        await m.scrollIntoViewIfNeeded();
        await d.highlight(m.locator('xpath=ancestor::div[contains(@class,"border-t")][1]'));
        await d.sleep(5000);
        await d.unhighlight();
      } },
    { id: 'gdi', chapter: 'The gas cap drive index', chapterSub: 'At m = 0.45',
      say: 'On the Run tab, eighteen million barrels, with the gas cap supplying nought point three nine eight of the voidage at the last survey.',
      sub: 'On the Run tab, 18 million barrels, with the gas cap supplying 0.398 of the voidage at the last survey.',
      do: async (d) => {
        await d.click(tab(d, 'Run'));
        await d.sleep(1200);
        await expectText(d, t(d, 'mbal-result-card'), /OOIP\s*18\.00 MMSTB[\s\S]*Gas cap \(GDI\)\s*0\.398/, 'm 0.45');
        await d.highlight(t(d, 'mbal-result-card'));
        await d.sleep(3500);
        await d.unhighlight();
      } },
    { id: 'm03', chapter: 'How m moves the answer', chapterSub: 'Too small a gas cap',
      say: 'Tell the model the gas cap is smaller, nought point three, and run. The expansion the gas cap really supplied now has to come from somewhere, so the oil in place grows to twenty two point two six million barrels.',
      sub: 'Tell the model the gas cap is smaller, 0.3, and run. The expansion the gas cap really supplied now has to come from somewhere, so the oil in place grows to 22.26 million barrels.',
      do: async (d) => {
        await setM(d, '0.3');
        await runMbal(d, { onCamera: true });
        await expectText(d, t(d, 'mbal-result-card'), /OOIP\s*22\.26 MMSTB/, 'm 0.3');
        await d.highlight(ooip(d));
        await d.sleep(3000);
        await d.unhighlight();
      } },
    { id: 'm06',
      say: 'Too large a gas cap, nought point six, and it shrinks to fifteen point one one. m and the oil in place trade against each other, so m deserves as much care as the pressures.',
      do: async (d) => {
        await setM(d, '0.6');
        await runMbal(d, { onCamera: true });
        await expectText(d, t(d, 'mbal-result-card'), /OOIP\s*15\.11 MMSTB/, 'm 0.6');
        await d.highlight(ooip(d));
        await d.sleep(3000);
        await d.unhighlight();
      } },
    { id: 'hm', chapter: 'Fitting m', chapterSub: 'History match',
      say: 'When the logs leave m uncertain, the history match can fit it with the oil in place. Tick m and match, starting from the wrong value of nought point six. The match pulls m back to nought point five two two nine and the oil in place to sixteen point seven one five million, with wide intervals: m anywhere from nought point four seven to nought point five eight. The pressures alone cannot pin both. Take m from the logs, and let the match test it.',
      do: async (d) => {
        await d.click(seg(d, 'History match'));
        await d.sleep(1500);
        await d.click(d.page.getByLabel('Fit Gas cap ratio m'));
        await d.sleep(600);
        await d.click(d.page.getByRole('button', { name: /Run history match/ }));
        await d.waitText('mbal-hm-status-line', /Converged|Stopped|iterations/, { timeout: 240000 });
        await d.sleep(1200);
        await expectText(d, t(d, 'mbal-hm-matched'), /STOIIP N \(MMSTB\)\s*15\.111\s*16\.715[\s\S]*Gas cap ratio m \(fraction\)\s*0\.6000\s*0\.5229\s*0\.4737 to 0\.5774/, 'm fitted');
        const tbl = t(d, 'mbal-hm-matched').locator('xpath=ancestor::table[1]');
        await tbl.evaluate((e) => e.scrollIntoView({ behavior: 'smooth', block: 'center' }));
        await d.sleep(800);
        await d.highlight(tbl);
        await d.sleep(4500);
        await d.unhighlight();
      },
      wait: async (d) => { await setM(d, '0.45', false); await runMbal(d); },
      waitLabel: 'Back to m = 0.45' },
    { id: 'next', chapter: 'Next', chapterSub: 'Aquifer models',
      say: 'Next, the aquifer: which model, and what each one does to the answer.',
      do: async (d) => { await d.sleep(2000); } },
  ],
};
